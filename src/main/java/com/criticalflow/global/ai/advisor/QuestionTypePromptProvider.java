package com.criticalflow.global.ai.advisor;

import com.criticalflow.domain.conversation.entity.QuestionType;
import org.springframework.stereotype.Component;

@Component
public class QuestionTypePromptProvider {

    public String getPromptFor(QuestionType type) {
        return switch (type) {
            case TYPE_A -> """
                    TYPE A — 개념 정의 확인 및 적용 탐구
                      목표: 학습자가 새로운 용어나 개념을 자신의 말로 설명할 수 있는지 확인하고,
                           이론만 있는 경우 실제 상황에 적용할 수 있는지도 함께 탐구한다.
                      질문 템플릿 (하나 선택):
                        - "[용어]에 대해 찾아보지 않고 본인의 말로 설명해줄 수 있어?"
                        - "[개념]이 실제로 어떤 문제를 해결하기 위해 등장했나요?"
                        - "지금까지 개발하거나 공부하면서 [개념]이 필요했던 순간을 떠올릴 수 있나요?"
                    """;
            case TYPE_B -> """
                    TYPE B — 설계 의도 탐침
                      목표: 학습자가 특정 방식을 의도적으로 선택했는지 확인한다.
                      의도: [방식]과 대안 [대안]의 트레이드오프를 스스로 설명하게 한다.
                      예시(노트 내용에 맞게 변형, 복사 금지):
                        - "[방식] 대신 [대안]을 안 쓴 이유는 뭘까?"
                        - "[방식]을 고르면서 어떤 점을 포기한 걸까?"
                    """;
            case TYPE_C -> """
                    TYPE C — 과거 학습 연계 (Spaced Recall)
                      목표: 현재 학습 내용과 이전에 공부한 개념을 연결하여 장기 기억을 강화한다.

                      [질문 구성 절차 — 반드시 이 순서로]
                      1. Current Note에서 핵심 개념/키워드 하나를 추출한다 → [현재 개념]
                      2. Retrieved Past Context에서 [현재 개념]과 가장 연관된 개념/키워드 하나를 추출한다 → [과거 개념]
                      3. 두 개념의 관계 유형을 판단하고, 그 의도에 맞는 질문을 [A]·[B]의 실제 내용에 맞춰 새로 만든다.
                         아래 예시 문장은 패턴 참고용이며 그대로 복사하지 않는다. 연결어와 표현은 두 개념의 성격에 맞게 자연스럽게 바꾼다.
                         · 확장 (과거가 현재의 기초): 현재 개념이 과거 개념을 어떻게 발전시키는지 묻는다.
                           예) "전에 [A]를 배웠는데, [B]는 그걸 어떤 방향으로 확장한 걸까?"
                         · 대조 (같은 문제, 다른 해법): 둘을 언제·왜 다르게 고르는지 묻는다.
                           예) "[A] 대신 [B]를 써야 하는 상황은 어떤 경우일까?"
                         · 기반 (과거가 현재의 전제): 과거 개념이 빠지면 현재 개념이 어떻게 달라지는지 묻는다.
                           예) "[A]가 없다면 [B]는 어떻게 달라질까?"
                      4. [A]·[B]에는 반드시 실제 추출한 용어를 채운다. 추상 표현("이 개념", "이것")과 대괄호 자리표시자는 출력에 남기지 않는다.
                      5. 예시의 문장 구조를 매번 그대로 반복하지 않는다. 질문은 두 개념에 어울리는 자연스러운 한 문장으로 만든다.
                      - 관계 유형이 불분명하면 확장 의도를 기본으로 사용한다.
                    """;
            case TYPE_D -> """
                    TYPE D — 심층 사고 탐구
                      목표: 엣지케이스·실패 케이스·경계 조건을 탐구한다.
                      의도: [전제 조건]이 깨질 때 무슨 일이 생기는지 추론하게 한다.
                      예시(노트 내용에 맞게 변형):
                        - "[전제 조건]이 성립하지 않으면 어떤 문제가 생길까?"
                        - "[입력]이 극단적인 경우 [개념]은 어떻게 동작할까?"
                    """;
            case TYPE_E -> """
                    TYPE E — 코드 동작 탐침
                      목표: 학습자가 코드가 실제로 어떻게 동작하는지 이해하고 있는지 확인한다.
                      질문 템플릿 (하나 선택):
                        - "이 코드의 시간복잡도는 어떻게 되나요? 왜 그렇게 생각하나요?"
                        - "이 코드에서 [특정 라인]이 없다면 어떤 일이 생길까요?"
                        - "이 함수에 [엣지케이스 입력]을 넣으면 어떻게 동작할까요?"
                      제약: 수정된 코드나 정답 구현을 절대 제공하지 않는다 (LAW 1).
                    """;
        };
    }

    public String inject(String systemText, QuestionType type) {
        return systemText.replace("{selected_question_type}", getPromptFor(type));
    }
}
