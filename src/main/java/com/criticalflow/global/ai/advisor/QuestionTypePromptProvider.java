package com.criticalflow.global.ai.advisor;

import com.criticalflow.domain.conversation.entity.QuestionType;
import org.springframework.stereotype.Component;

@Component
public class QuestionTypePromptProvider {

    public String getPromptFor(QuestionType type) {
        return switch (type) {
            case TYPE_A -> """
                TYPE A — 개념 정의 확인 및 적용 탐구
                  목표: 학습자가 새 용어·개념을 자기 말로 설명할 수 있는지 확인하고, 이론만 있으면 실제 적용까지 탐구한다.
                  의도: [용어]의 의미를 스스로 설명하게 하거나, [개념]이 어떤 문제를 푸는지 떠올리게 한다.
                  예시 (하나를 골라 노트 내용에 맞게 변형, 복사 금지):
                    - "[용어]를 찾아보지 않고 본인 말로 설명해줄 수 있어?"
                    - "[개념]은 원래 어떤 문제를 풀려고 등장한 걸까?"
                    - "공부하거나 개발하면서 [개념]이 필요했던 순간이 있었어?"
                """;
            case TYPE_B -> """
                TYPE B — 설계 의도 탐침
                  목표: 학습자가 특정 방식을 의도적으로 선택했는지 확인한다.
                  의도: 선택한 [방식]과 대안 [대안] 사이의 트레이드오프를 스스로 설명하게 한다.
                  예시 (하나를 골라 노트 내용에 맞게 변형, 복사 금지):
                    - "[방식] 대신 [대안]을 안 쓴 이유는 뭘까?"
                    - "[방식]을 고르면서 어떤 점을 포기한 걸까?"
                """;
            case TYPE_C -> """
                TYPE C — 과거 학습 연계
                  목표: 현재 학습 내용과 이전에 공부한 개념을 연결해 이해를 강화한다.

                  [질문 구성 절차 — 반드시 이 순서로]
                  1. Current Note에서 핵심 개념/키워드 하나를 뽑는다 → [현재 개념]
                  2. Retrieved Past Context에서 [현재 개념]과 가장 연관된 개념/키워드 하나를 뽑는다 → [과거 개념]
                     ([과거 개념]은 반드시 Retrieved Past Context에 실제로 등장한 용어여야 하며, 없으면 지어내지 않는다.)
                  3. 두 개념의 관계 유형을 판단하고, 그 의도에 맞는 질문을 두 개념의 실제 내용에 맞춰 새로 만든다.
                     아래 예시는 패턴 참고용이며 그대로 복사하지 않는다.
                     · 확장 (과거가 현재의 기초): 현재가 과거를 어떻게 발전시키는지 묻는다.
                       예) "전에 [과거 개념]을 배웠는데, [현재 개념]은 그걸 어떤 방향으로 확장한 걸까?"
                     · 대조 (같은 문제, 다른 해법): 둘을 언제·왜 다르게 고르는지 묻는다.
                       예) "[과거 개념] 대신 [현재 개념]을 써야 하는 상황은 어떤 경우일까?"
                     · 기반 (과거가 현재의 전제): 과거가 빠지면 현재가 어떻게 달라지는지 묻는다.
                       예) "[과거 개념]이 없다면 [현재 개념]은 어떻게 달라질까?"
                  4. 관계 유형이 불분명하면 확장 의도를 기본으로 사용한다.
                  제약: 과거 노트 내용은 두 개념을 잇는 단서로만 쓰고, 정의·정답을 직접 제시하지 않는다.
                """;
            case TYPE_D -> """
                TYPE D — 심층 사고 탐구
                  목표: 표면적 이해를 넘어 엣지케이스·실패 케이스·경계 조건을 탐구한다.
                  의도: [전제 조건]이 깨지거나 [입력]이 극단적일 때 무슨 일이 생기는지 추론하게 한다.
                  예시 (하나를 골라 노트 내용에 맞게 변형, 복사 금지):
                    - "[전제 조건]이 성립하지 않으면 어떤 문제가 생길까?"
                    - "[입력]이 극단적인 경우 [개념]은 어떻게 동작할까?"
                """;
            case TYPE_E -> """
                TYPE E — 코드 동작 탐침
                  목표: 학습자가 코드가 실제로 어떻게 동작하는지 이해하는지 확인한다.
                  의도: 코드의 동작·복잡도·엣지케이스를 학습자가 직접 추론하게 한다.
                  예시 (하나를 골라 노트 내용에 맞게 변형, 복사 금지):
                    - "이 코드의 시간복잡도가 왜 그렇게 되는지 설명해줄 수 있어?"
                    - "[특정 라인]이 없다면 어떤 일이 생길까?"
                    - "[엣지케이스 입력]을 넣으면 이 함수는 어떻게 동작할까?"
                  제약: 수정된 코드나 정답 구현을 절대 제공하지 않는다 (LAW 1).
                """;
        };
    }

    public String inject(String systemText, QuestionType type) {
        return systemText.replace("{selected_question_type}", getPromptFor(type));
    }
}
